// Regenerates data/learnAi/registry.generated.ts from the files in data/learnAi/lessons/.
// Run after adding a lesson file:  node scripts/learn-ai/gen-index.mjs
// Order on the site still comes from PLAN in data/learnAi/tracks.ts.
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, 'data', 'learnAi', 'lessons')
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && !f.startsWith('_'))
  .sort()

const lines = [
  '// AUTO-GENERATED by scripts/learn-ai/gen-index.mjs. Do not edit by hand.',
  "import type { Lesson } from './types'",
  ...files.map((f, i) => `import { lesson as l${i} } from './lessons/${f.replace(/\.ts$/, '')}'`),
  '',
  'export const LESSON_LIST: Lesson[] = [',
  ...files.map((_, i) => `  l${i},`),
  ']',
  '',
]
writeFileSync(join(root, 'data', 'learnAi', 'registry.generated.ts'), lines.join('\n'))
console.log(`registry.generated.ts: ${files.length} lessons`)
