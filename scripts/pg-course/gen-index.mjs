// Regenerates data/pgCourse/registry.generated.ts from the files in data/pgCourse/lessons/.
// Run after adding a lesson file:  node scripts/pg-course/gen-index.mjs
// Order on the site still comes from PG_PLAN in data/pgCourse/tracks.ts.
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, 'data', 'pgCourse', 'lessons')
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && !f.startsWith('_'))
  .sort()

const lines = [
  '// AUTO-GENERATED by scripts/pg-course/gen-index.mjs. Do not edit by hand.',
  "import type { PgLesson } from './types'",
  ...files.map((f, i) => `import { lesson as l${i} } from './lessons/${f.replace(/\.ts$/, '')}'`),
  '',
  'export const PG_LESSON_LIST: PgLesson[] = [',
  ...files.map((_, i) => `  l${i},`),
  ']',
  '',
]
writeFileSync(join(root, 'data', 'pgCourse', 'registry.generated.ts'), lines.join('\n'))
console.log(`registry.generated.ts: ${files.length} lessons`)
