// Regenerates data/pgCourse/batch/registry.generated.ts from data/pgCourse/batch/weeks/*.ts.
// Run after adding or renaming a week file:  node scripts/pg-course/gen-batch.mjs
// Order on the site comes from each file's `week` number.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, 'data', 'pgCourse', 'batch', 'weeks')
if (!existsSync(dir)) mkdirSync(dir, { recursive: true })
const files = readdirSync(dir)
  .filter((f) => /^week-\d+\.ts$/.test(f))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]))

const lines = [
  '// AUTO-GENERATED by scripts/pg-course/gen-batch.mjs. Do not edit by hand.',
  "import type { BatchWeek } from './types'",
  ...files.map((f, i) => `import { week as w${i} } from './weeks/${f.replace(/\.ts$/, '')}'`),
  '',
  'export const BATCH_WEEK_LIST: BatchWeek[] = [',
  ...files.map((_, i) => `  w${i},`),
  ']',
  '',
]
writeFileSync(join(root, 'data', 'pgCourse', 'batch', 'registry.generated.ts'), lines.join('\n'))
console.log(`batch registry.generated.ts: ${files.length} weeks`)
